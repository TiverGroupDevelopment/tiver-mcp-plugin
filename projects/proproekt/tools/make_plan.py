"""План моделирования ПроПроекта (Markdown) по jobs.json.

    python -I make_plan.py <jobs.json> <план.md>
"""
import json
import os
import sys
from collections import Counter

CAT = {'OST_Furniture': 'Мебель', 'OST_SpecialityEquipment': 'Специальное оборудование', 'OST_GenericModel': 'Обобщенные модели',
       'OST_Casework': 'Шкафы', 'OST_MechanicalEquipment': 'Оборудование', 'OST_PlumbingFixtures': 'Сантехнические приборы',
       'OST_ElectricalFixtures': 'Электрические приборы'}
KIND = {'box': 'кубик', 'cylinder': 'цилиндр', 'rebuild': 'перенос исходника'}


def size(job):
    s = job['size']
    if job['kind'] == 'cylinder':
        return f'Ø{s[0]:g}×{s[2]:g}'
    return '×'.join(f'{x:g}' for x in s)


def main(jobs_path, out_path):
    jobs = json.load(open(jobs_path, encoding='utf-8'))
    kinds = Counter(j['kind'] for j in jobs)
    cats = Counter(CAT.get(j['category'], j['category']) for j in jobs)
    rotated = [j for j in jobs if j.get('map', {}).get('rotate')]
    assumed = [j for j in jobs if any('габаритов нет' in n for n in j['notes'])]
    face = [j for j in jobs if j['faceBased']]
    by_source = Counter(j['source'] for j in jobs if j['source'])

    L = ['# План моделирования семейств ПроПроекта (Revit 2019)', '',
         'Сгенерирован из `jobs.json` скриптом [tools/make_plan.py](tools/make_plan.py) по таблице «Семейства» (лист «Уникальные позиции») '
         'и снимкам исходных семейств. Правила — профиль [`proproekt`](../../rules/ПроПроект/profile.json).', '',
         '## Исходные данные', '',
         '- Спецификация ИОС6.ТХ1, листы 34–113: 668 позиций в 73 разделах (72 помещения и «Улица»), 161 уникальная строка таблицы.',
         f'- Семейств к моделированию: {len(jobs)}. Строки-дубли с одинаковым именем (4.38, 7.04 — разные пробелы в PDF) дают одно семейство.',
         f'- Исходные семейства — {len(by_source)} из модели `К01_ТХ_П_R24.rvt` (снимок в `ПроПроект3/исходные семейства`).', '',
         '## Способ построения', '',
         '| Способ | Семейств | Как |', '|---|---|---|',
         f'| кубик | {kinds["box"]} | одно выдавливание по габариту Ш×Г×В, центр в плане, низ на 0 |',
         f'| цилиндр | {kinds["cylinder"]} | выдавливание круга Ø×H |',
         f'| перенос исходника | {kinds["rebuild"]} | формы исходного семейства по эскизам с подгонкой под габарит; вложенные семейства — их формами |',
         '', 'Перенос исходника:',
         '- Преобразование: при необходимости поворот на 90° в плане (длинная сторона — вдоль ширины), масштаб по осям под Ш×Г×В, центр в плане — в начало координат, низ — на уровень 0.',
         '- Формы: выдавливание, вращение, сопряжение, сдвиг, сдвиг-сопряжение — тем же видом формы. Пустотные формы вырезают твёрдые (объединение геометрии).',
         '- Упрощения LOD200, если Revit не принимает форму: сдвиг — брусья по сегментам пути с сечением профиля; иначе — короб по габариту формы.',
         '- Подгонка габарита: построить → измерить по рёбрам → пересобрать с поправкой (до 3 проходов, лучший). Допуск — 1 мм.',
         '', '## Шаблоны и категории', '',
         '- Шаблон: `Метрическая система, типовая модель.rft`; настенные исходники на основе грани (Т39, Т7, сушилка для рук, рулонная штора) — '
         '`Метрическая система, типовая модель на основе грани.rft`. Категория задаётся после создания.', '',
         '| Категория 2019 | Семейств |', '|---|---|']
    L += [f'| {k} | {v} |' for k, v in cats.most_common()]
    L += ['', '## Параметры и имя', '',
          '- `ADSK_Наименование` (тип), `ADSK_Марка` (тип), `ADSK_Позиция` (экземпляр) из ФОП2019; значения — колонки G, J, I таблицы.',
          '- Один типоразмер, его имя = имя семейства; файл `ПроПроект3/rvt/rfa/<Имя семейства>.rfa`.', '',
          f'## Допущения по габаритам ({len(assumed)})', '',
          'В спецификации нет габаритов — принято (PP-08):', '', '| Семейство | Принято |', '|---|---|']
    L += [f'| {j["family"]} | {"; ".join(n for n in j["notes"] if "габаритов нет" in n)} |' for j in assumed]
    L += ['', f'## Поворот исходника на 90° ({len(rotated)})', '',
          'Длинная сторона исходника лежала вдоль Y, а по спецификации ширина больше глубины: ' +
          ', '.join(j['family'].split('_')[0] for j in rotated) + '.', '',
          f'## На основе грани ({len(face)})', '', ', '.join(j['family'] for j in face) + '.', '',
          '## Порядок работ', '',
          '1. Задания: `tools/make_jobs.py` по выгрузке листа «Уникальные позиции» и снимкам исходников.',
          '2. Построение: скрипт `scripts/build_families` в Revit 2019 партиями по 8 (лог `моделирование/build-log.jsonl`).',
          '3. Проверка: `scripts/verify_families` (версия, имя, категория, параметры и GUID, типоразмер, габарит, точка вставки, импорт) и '
          '`tools/check_rules.mjs` (команда плагина `check_family_rules` с проверками профиля `proproekt`).',
          '4. Картинки: `tools/render_proof.py` — изометрия и три проекции с габаритами.',
          '5. Отчёт: `tools/make_report.py`.', '',
          '## Все семейства', '',
          '| № | Семейство | Способ | Исходник | Категория | Габарит, мм | Строки таблицы |', '|---|---|---|---|---|---|---|']
    for i, j in enumerate(jobs, 1):
        L.append(f'| {i} | {j["family"]} | {KIND[j["kind"]]}{" (на грани)" if j["faceBased"] else ""} | {j["source"] or "—"} | '
                 f'{CAT.get(j["category"], j["category"])} | {size(j)} | {", ".join(map(str, j["rows"]))} |')
    open(out_path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('план:', len(jobs), 'семейств')


if __name__ == '__main__':
    main(*sys.argv[1:3])
